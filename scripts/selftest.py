def synth(path):
    doc = pymupdf.open()
    for i, (title, sub, lines) in enumerate(PAGES, 1):
        page = doc.new_page(width=595, height=842)
        page.insert_text((64, 90), title, fontsize=22)
        page.insert_text((64, 124), sub, fontsize=12)
        y = 170
        for ln in lines:
            page.insert_text((64, y), ln, fontsize=11)
            y += 22
        page.insert_text((500, 800), 'P%d' % i, fontsize=10)
    doc.save(path)
    doc.close()
    return path


def run_pipeline(cmd):
    """实时透传子进程输出，并在「长时间没有新输出」时点名当前步骤。

    返回值 (全部输出文本, 退出码)。超时被 kill 时退出码为 None。
    """
    buf = []
    lock = threading.Lock()
    state = {'last': time.time(), 'step': '(启动中)', 'done': False}

    proc = subprocess.Popen(
        cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
        text=True, encoding='utf-8', errors='replace', bufsize=1,
    )

    def reader():
        try:
            for line in proc.stdout:
                with lock:
                    buf.append(line)
                    state['last'] = time.time()
                    m = re.search(r'▶\s*(.+?)\s*$', line.rstrip())
                    if m:
                        state['step'] = m.group(1)
                sys.stdout.write(line)
                sys.stdout.flush()
        finally:
            with lock:
                state['done'] = True

    th = threading.Thread(target=reader, daemon=True)
    th.start()

    t0 = time.time()
    warned = set()
    while True:
        with lock:
            done, idle, step = state['done'], time.time() - state['last'], state['step']
        if done and proc.poll() is not None:
            break
        if idle > STALL_WARN and step not in warned:
            warned.add(step)
            print('\n⚠ 已 %d 秒没有新输出 —— 当前停在：%s\n'
                  '  （真卡住的话多半是这一步的浏览器/探针没退，'
                  '见 references/pitfalls.md 第 29、36 条）\n' % (int(idle), step), flush=True)
        if time.time() - t0 > HARD_LIMIT:
            proc.kill()
            print('\n✘ 流水线超过 %d 秒仍未结束，已终止。最后停在：%s\n' % (HARD_LIMIT, step),
                  flush=True)
            break
        time.sleep(1)
    th.join(timeout=5)
    return ''.join(buf), proc.poll()


def semantic_path(base, pdf):
    """语义路线：--stage plan → 校对 outline → 改写确认 → --outline 建骨架 → build → 三校验。

    这是「先定结构、再写内容」路线的自测，与上面机械路线互补。synth 造的英文 PDF
    没有书签/编号信号，plan_outline 会退化为 fallback（每 8 页一段），这里照单全收
    再程序化把它改成「两段语义结构」——这一步模拟的正是 agent 填语义 + 用户确认。
    """
    sem = os.path.join(base, 'semantic')
    os.makedirs(sem, exist_ok=True)
    checks = []
    outline_path = os.path.join(sem, '_plan', 'outline.json')

    # ① --stage plan：只抽文字层出 outline 草案（默认不渲染图），不建骨架、不构建；
    #    逐页图在 ④ 的 run_all --skip-init 里照常渲染（该次没传 --skip-prepare）
    out, rc = run_pipeline([sys.executable, '-u', os.path.join(HERE, 'run_all.py'),
                            pdf, '--out', sem, '--stage', 'plan'])
    checks.append(('① --stage plan 退出码 0', rc == 0))
    checks.append(('① 产出 outline 草案', os.path.exists(outline_path)))

    # ② 校对 outline：结构、覆盖性、封面字段、草案状态
    d = None
    if os.path.exists(outline_path):
        d = json.load(open(outline_path, encoding='utf-8'))
        secs = d.get('sections') or []
        seen = [n for s in secs for n in (s.get('pages') or [])]
        checks.append(('② outline.schema=v1', d.get('schema') == 'outline/v1'))
        checks.append(('② sections 非空', len(secs) >= 1))
        checks.append(('② 页码覆盖 2..N 且不重复',
                       sorted(seen) == list(range(2, len(PAGES) + 1))))
        checks.append(('② cover 字段存在', isinstance(d.get('cover'), dict)))
        checks.append(('② 草案未确认（confirmed=false）', d.get('confirmed') is False))

    # ③ 程序化改写为「确认过的两段语义结构」，模拟 agent 填语义 + 用户确认
    if d is not None:
        d['source'] = 'semantic'
        d['sections'] = [
            {'key': 's1', 'name': 'Counting', 'pages': [2, 3], 'origin': 'semantic',
             'part_index': 1, 'toc_label': '1 · Counting（P2–P3）'},
            {'key': 's2', 'name': 'Smoothing and wrap-up', 'pages': [4, 5, 6],
             'origin': 'semantic', 'part_index': 2,
             'toc_label': '2 · Smoothing and wrap-up（P4–P6）'},
        ]
        d['confirmed'] = True
        d['confirmed_by'] = 'selftest'
        open(outline_path, 'w', encoding='utf-8').write(
            json.dumps(d, ensure_ascii=False, indent=2) + '\n')
    checks.append(('③ 改写 outline 为两段语义结构',
                   d is not None and len(d.get('sections') or []) == 2))

    # ④ --outline 建骨架 → build → 三校验（run_all --skip-init）
    if d is not None:
        _, rc2 = run_pipeline([sys.executable, '-u', os.path.join(HERE, 'init_project.py'),
                               pdf, '--out', sem, '--outline', outline_path])
        checks.append(('④ init --outline 建骨架退出码 0', rc2 == 0))
        out3, rc3 = run_pipeline([sys.executable, '-u', os.path.join(HERE, 'run_all.py'),
                                  pdf, '--out', sem, '--skip-init'])
        checks.append(('④ build + 体检退出码 0', rc3 == 0))
        cfg_path = os.path.join(sem, 'config.json')
        if os.path.exists(cfg_path):
            cfg = json.load(open(cfg_path, encoding='utf-8'))
            checks.append(('④ config.outline.confirmed=true',
                           bool((cfg.get('outline') or {}).get('confirmed'))))
            seg_names = [g[0] for g in (cfg.get('groups') or [])]
            checks.append(('④ 目录按语义切成 2 段',
                           any(x.startswith('1 ·') for x in seg_names)
                           and any(x.startswith('2 ·') for x in seg_names)))
        checks.append(('④ 产物已生成', any(f.endswith('-逐页精解.html') for f in os.listdir(sem))))
        checks.append(('④ check_ui ALL PASS', re.search(r'ALL PASS', out3) is not None))
        checks.append(('④ probe_marks PASS', re.search(r'RESULT: PASS', out3) is not None))
        checks.append(('④ probe_doc 报进度', re.search(r'内容进度', out3) is not None))
        checks.append(('④ run_all 判定全绿', re.search(r'机械部分全绿', out3) is not None))
    return checks


def course_path(base):
    """课程路线：把前两条路线已经建好的产物**就地组成一门两讲小课程**，走一遍课程层。

    为什么不另造一份 PDF：课程层是**纯静态**的（coursekit 不启浏览器，见 pitfalls 第 29 条），
    它消费的只是各讲产物 HTML。前两条路线跑完，磁盘上已经躺着两份真实产物
    （机械路线一份、语义路线一份）—— 直接拿它们当讲次，比再造 PDF 更省时间，
    而且用的是**真实产物形态**而不是手搓的迷你样例。

    本函数做四件事：
      ① 复制两讲目录到 `base/course/lecture-01-zh` 与 `lecture-02-en`，
         并把 `config.json` 里 `out` / `pdf` 的**绝对路径改写到副本内**
         （不改的话 course_index 读的还是原件，断言对象错位，等于没测）；
      ② 给 L01 的产物补上 v2 声明（data-concepts / data-pays-off / data-forward、
         要点、术语行、一张 .xref 跨讲卡）—— 合成 PDF 没有内容作者，
         不补的话 ③④⑤⑥ 组会是「0 个术语 0 条要点」的空转 PASS，
         那正是 pitfalls 第 44 条要防的形态；
      ③ 跑 course_init → run_course --sync --no-probe；
      ④ **反向注入**：把一条 .xref 指向坏锚点，重跑体检，必须报 FAIL ——
         证明刚才是真的在查，而不是「永远 PASS」。

    返回断言列表（与另两条路线同格式）。
    """
    checks = []
    course = os.path.join(base, 'course')
    if os.path.exists(course):
        shutil.rmtree(course, ignore_errors=True)
    os.makedirs(course, exist_ok=True)

    # 两讲：L01 = 机械路线产物（补 v2 声明），L02 = 语义路线产物（纯 v1，当对照）
    lectures = (('lecture-01-zh', base), ('lecture-02-en', os.path.join(base, 'semantic')))
    copied = True
    for name, src in lectures:
        dst = os.path.join(course, name)
        try:
            shutil.copytree(src, dst, ignore=shutil.ignore_patterns(
                'course', '_extract', '_katex', 'content'))
        except OSError:
            copied = False
            continue
        # 产物绝对路径改写进副本
        cfg_p = os.path.join(dst, 'config.json')
        cfg = None
        if os.path.exists(cfg_p):
            cfg = json.load(open(cfg_p, encoding='utf-8'))
            for k in ('out', 'pdf'):
                if cfg.get(k):
                    cfg[k] = cfg[k].replace(os.path.normpath(src), os.path.normpath(dst))
            open(cfg_p, 'w', encoding='utf-8').write(
                json.dumps(cfg, ensure_ascii=False, indent=2) + '\n')
    checks.append(('⓪ 课程样例：两讲目录就位',
                   copied and all(os.path.exists(os.path.join(course, n, 'config.json'))
                                  for n, _ in lectures)))

    # ② 给 L01 补 v2 声明
    prod_rel = patch_course_lecture(os.path.join(course, 'lecture-01-zh'))
    checks.append(('⓪ 课程样例：L01 补上 v2 声明', prod_rel is not None))

    # ③ 初始化 + 全量同步（跳过浏览器探针 —— 课程层体检是静态的）
    _, rc0 = run_pipeline([sys.executable, '-u',
                           os.path.join(HERE, 'course_init.py'), course,
                           '--name', '自检课程 · selftest'])
    checks.append(('⑤ course_init 退出码 0', rc0 == 0))
    out_c, rc_c = run_pipeline([sys.executable, '-u',
                                os.path.join(HERE, 'run_course.py'), course,
                                '--sync', '--no-probe'])
    checks.append(('⑤ run_course --sync 全绿', rc_c == 0))
    checks.append(('⑤ 课程入口 index.html 已生成',
                   os.path.exists(os.path.join(course, 'index.html'))))

    # ⑤ 体检输出：必须 ALL PASS，**且断言对象不能是空的**
    # 单独再跑一次 course_check.py 取它的完整输出 —— run_course 成功时只回显
    # 步骤名、不回显子步骤的输出，从 run_course 的输出里 grep 不到明细。
    out_ck, rc_ck = run_pipeline([sys.executable, '-u',
                                  os.path.join(HERE, 'course_check.py'), course])
    checks.append(('⑤ course_check ALL PASS',
                   rc_ck == 0 and re.search(r'结果: ALL PASS', out_ck) is not None))
    # 这一条是「防空转」：0 个术语 0 条要点也能 ALL PASS，但那说明样例没铺开、
    # ③⑤⑥ 组什么都没查（pitfalls 第 44 条的形态）。
    m = re.search(r'统计：(\d+) 讲 ｜ (\d+) 条入口链接 ｜ (\d+) 个术语 ｜ (\d+) 条要点', out_ck)
    if m:
        n_lec, n_link, n_term, n_kp = (int(x) for x in m.groups())
        checks.append(('⑤ 体检确实铺开了（讲/链接/术语/要点都 > 0）',
                       n_lec > 0 and n_link > 0 and n_term > 0 and n_kp > 0))
    else:
        checks.append(('⑤ 体检确实铺开了（讲/链接/术语/要点都 > 0）', False))
    checks.append(('⑤ .xref 跨讲卡被真的检查到', '检查了 1 条 .xref 外链' in out_ck))

    # ⑤b 公式渲染链（pitfalls 第 49/50 条的守卫）。
    # 这两条断言各有分工，缺一不可：
    #   · 空转守卫：样例里必须**真的有公式**（否则下面两条永远为真、等于没测）；
    #   · 链路断言：内联了 KaTeX、且可见正文里没有〔公式〕占位符。
    # 只内联 KaTeX 而抽取器把公式塌成占位符（第 50 条），或标签写坏了截断脚本
    # （第 49 条），都会被第二条抓住。
    entry_p = os.path.join(course, 'index.html')
    raw = open(entry_p, encoding='utf-8').read() if os.path.exists(entry_p) else ''
    # 公式标签在产物里是 `<script type="math/tex">`；主页导出到 cdata 时 `<` 会转义
    n_src = len(re.findall(r'<script\b[^>]*\btype="math/tex', raw, re.I))
    n_esc = raw.count(r'math/tex')
    checks.append(('⓪ 课程样例：要点/术语里确实带了公式（空转守卫）',
                   n_src + n_esc > 0))
    checks.append(('⑤ 入口页内联了 KaTeX', 'katex.min.js' in raw or 'katex.render' in raw))
    # 可见正文（挖掉 script / style / **HTML 注释**）里不许剩〔公式〕——那是留给检索索引的记号。
    # ⚠ 必须用 coursekit.body_html()，与 course_check.py 的判据**同源**：自己写个粗糙的
    # 「剥 script」正则会漏挖注释，而 `course-shell.html` 的注释里正好有「〔公式〕」这个词，
    # 于是误报（2026-10-15 实测踩到）。判据同源是这个套件反复吃过的教训（pitfalls 第 43/44 条）。
    import coursekit  # noqa: E402  （HERE 已在模块顶部加进 sys.path）
    vis = coursekit.body_html(raw)
    checks.append(('⑤ 可见正文里没有〔公式〕占位符', '〔公式〕' not in vis))

    # ④ 反向注入：坏锚点必须被抓到
    checks.append(reverse_check_course(course, prod_rel))
    return checks


def patch_course_lecture(lec_dir):
    """给一讲的产物补上 v2 声明与三张卡的示例内容；返回产物相对路径（失败给 None）。

    补的都是**真实课件里内容作者会写的东西**（见 templates/content-skeleton/20_page.html
    与 examples/section-template.html）—— 这里只是把「内容作者」这一环程序化，
    好让课程层的 ③④⑤⑥ 组有真实的断言对象。
    """
    cfg_p = os.path.join(lec_dir, 'config.json')
    if not os.path.exists(cfg_p):
        return None
    cfg = json.load(open(cfg_p, encoding='utf-8'))
    out = cfg.get('out') or ''
    prod = out if os.path.isabs(out) else os.path.normpath(os.path.join(lec_dir, out))
    if not os.path.exists(prod):
        return None
    html = open(prod, encoding='utf-8').read()
    rel = os.path.basename(prod)

    # a) 逐页区块挂上三个声明（p04 同时回收 L01 的 counting 伏笔、留下 smoothing-constant）
    for pid, extra in (
        ('p03', ' data-concepts="counting"'),
        ('p04', ' data-concepts="laplace-smoothing" data-pays-off="counting@L01:p03"'),
        ('p05', ' data-forward="smoothing-constant"'),
    ):
        tag = '<section class="pg" id="%s" data-page="%s">' % (pid, pid[1:].lstrip('0'))
        html = html.replace(tag, tag[:-1] + extra + '>', 1)

    # b) #keypoints：三条真要点（首条带 data-topic，验证要点↔术语互链）。
    #    第 4 条**带公式**：它是「要点/术语里的公式能不能在主页渲染」这条链的断言对象
    #    （pitfalls 第 50 条 —— 抽取器/汇总层漏搬富文本字段时，公式会静默退化成〔公式〕）。
    old = re.search(r'<ol class="kpl"[\s\S]*?</ol>', html)
    if old:
        new = ('<ol class="kpl">\n'
               '    <li data-at="#p03" data-topic="counting">'
               'Counting is the whole idea: estimate p(x) from frequencies.</li>\n'
               '    <li data-at="#p04">'
               'Smoothing exists to keep an unseen outcome from getting probability zero.</li>\n'
               '    <li data-at="#p05">'
               'The smoothing constant trades confidence for robustness.</li>\n'
               '    <li data-at="#p05">'
               'Estimate <script type="math/tex">\\hat{p}=\\frac{c+\\alpha}{N+\\alpha K}'
               '</script> with a small alpha.</li>\n'
               '  </ol>')
        html = html[:old.start()] + new + html[old.end():]

    # c) #glossary：两行真术语（第二行释义带公式）。**必须在 glossary 卡内定位**
    #    （产物有多个 <tbody>）
    gi = html.find('id="glossary"')
    if gi >= 0:
        tb = re.search(r'<tbody>[\s\S]*?</tbody>', html[gi:])
        if tb:
            new = ('<tbody>\n'
                   '      <tr data-concept="counting">'
                   '<td>Counting</td><td>counting</td>'
                   '<td>Estimate p(x) as count(x)/N.</td>'
                   '<td><a href="#p03">P3</a></td></tr>\n'
                   '      <tr data-concept="laplace-smoothing">'
                   '<td>Smoothing</td><td>Laplace smoothing</td>'
                   '<td>Add <script type="math/tex">\\alpha</script> to every count.</td>'
                   '<td><a href="#p04">P4</a></td></tr>\n'
                   '    </tbody>')
            a, b = gi + tb.start(), gi + tb.end()
            html = html[:a] + new + html[b:]

    # d) 一张 .xref 跨讲卡，指向 L02 的产物（验证跨讲外链的文件 + 锚点都可达）
    xref = ('<div class="xref"><b>Cross-deck:</b> lecture 2 '
            '<a href="../lecture-02-en/%s#p02">P2</a> takes this further.</div>' % rel)
    html = html.replace('<section class="pg" id="p04"', xref + '<section class="pg" id="p04"', 1)

    open(prod, 'w', encoding='utf-8', newline='').write(html)
    return rel


def reverse_check_course(course, prod_rel):
    """反向注入：把 L01 的 .xref 改成坏锚点 → 体检**必须**报 FAIL，然后复原。

    没有这一步，前面那条 ALL PASS 只证明了「脚本没崩」，没证明「脚本在查东西」。
    """
    prod = os.path.join(course, 'lecture-01-zh', prod_rel or '')
    if not prod_rel or not os.path.exists(prod):
        return ('⑤ 反向注入：坏锚点被 course_check 抓到', False)
    html = open(prod, encoding='utf-8').read()
    good = '../lecture-02-en/%s#p02' % prod_rel
    bad = '../lecture-02-en/%s#p88' % prod_rel
    if good not in html:
        return ('⑤ 反向注入：坏锚点被 course_check 抓到', False)
    open(prod, 'w', encoding='utf-8', newline='').write(html.replace(good, bad, 1))
    out, _ = run_pipeline([sys.executable, '-u',
                           os.path.join(HERE, 'course_check.py'), course])
    caught = (re.search(r'结果: FAILED', out) is not None
              and re.search(r'目标产物里没有 #p88', out) is not None)
    # 复原，并重跑索引让状态回到自洽（--keep 时留下的目录不该是坏的）
    open(prod, 'w', encoding='utf-8', newline='').write(html)
    run_pipeline([sys.executable, '-u',
                  os.path.join(HERE, 'course_index.py'), course])
    return ('⑤ 反向注入：坏锚点被 course_check 抓到', caught)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--keep', action='store_true', help='保留生成的项目目录')
    ap.add_argument('--dir', default=None, help='指定项目目录（默认系统临时目录）')
    a = ap.parse_args()

    base = long_path(a.dir or os.path.join(tempfile.gettempdir(), 'slides-kit-selftest'))
    if os.path.exists(base) and not a.keep:
        shutil.rmtree(base, ignore_errors=True)
    os.makedirs(base, exist_ok=True)
    pdf = os.path.join(base, 'selftest-deck.pdf')
    if not os.path.exists(pdf):
        synth(pdf)
    print('测试课件: %s (%.1f KB)' % (pdf, os.path.getsize(pdf) / 1024))

    # -u：让 run_all 的输出不缓冲，实时看得到进度
    cmd = [sys.executable, '-u', os.path.join(HERE, 'run_all.py'), pdf, '--out', base, '--force']
    print('开始跑流水线（实时输出如下，约 1~2 分钟）：\n', flush=True)
    t0 = time.time()
    out, rc = run_pipeline(cmd)
    print('\n流水线耗时 %.1f 秒，退出码 %s' % (time.time() - t0, rc))

    def has(pat):
        return re.search(pat, out) is not None

    checks = [
        ('骨架生成', os.path.exists(os.path.join(base, 'config.json'))),
        ('内容分片生成', len([f for f in os.listdir(os.path.join(base, 'content'))
                             if f.endswith('.html')]) >= 4),
        ('离线 KaTeX 就位', os.path.exists(os.path.join(base, '_katex', 'katex.offline.css'))),
        ('缩略图齐全', len([f for f in os.listdir(os.path.join(base, '_extract'))
                            if f.startswith('thumb_')]) == len(PAGES)),
        ('逐页大图齐全', len([f for f in os.listdir(os.path.join(base, '_extract'))
                              if f.startswith('page-')]) == len(PAGES)),
        ('产物已生成', any(f.endswith('-逐页精解.html') for f in os.listdir(base))),
        ('check_ui ALL PASS', has(r'ALL PASS')),
        ('probe_marks PASS', has(r'RESULT: PASS')),
        ('probe_doc 报出了进度', has(r'内容进度')),
        ('run_all 判定全绿', has(r'机械部分全绿')),
    ]

    # 语义路线：与上面的机械路线互补，两条都要能在本脚本里跑通
    print('\n' + '=' * 72)
    print('开始跑语义路线（--stage plan → 校对 outline → --outline → build → 三校验）：\n',
          flush=True)
    checks.extend(semantic_path(base, pdf))

    # 课程路线：把上面两条路线产出的**真实产物**就地组成一门两讲课，走一遍课程层。
    # 「有课程样例才跑」落在本函数内部：两讲的 config.json 或产物缺一，就整体跳过并说明，
    # 而不是让单讲场景在课程层报一堆看不懂的错。
    print('\n' + '=' * 72)
    print('开始跑课程路线（把两份真实产物组成两讲课 → 课程层体检 → 反向注入）：\n',
          flush=True)
    checks.extend(course_path(base))

    # 套件自身的文档口径：不属于「产物对不对」，但属于「套件健康吗」。
    # 接在这里而不是 run_all.py —— run_all 是给用户跑课件的流水线，
    # 让每个用户都体检一遍套件文档没有意义；selftest 才是「套件自己体检自己」。
    print('\n' + '=' * 72)
    print('开始体检套件自身的文档口径（check_docs.py）：\n', flush=True)
    out_docs, rc_docs = run_pipeline([sys.executable, '-u',
                                      os.path.join(HERE, 'check_docs.py')])
    checks.append(('check_docs 文档口径 ALL PASS',
                   rc_docs == 0 and re.search(r'ALL PASS', out_docs) is not None))

    print('=' * 72)
    bad = 0
    for name, ok in checks:
        print('  %s %s' % ('✔' if ok else '✘', name))
        bad += 0 if ok else 1
    print('=' * 72)
    print('自检结果: %s' % ('PASS' if not bad else 'FAIL（%d 项不通过）' % bad))
    if a.keep:
        print('保留目录: %s' % base)
    sys.exit(0 if not bad else 1)


if __name__ == '__main__':
    main()
